"""TMDB key/relay sync between devices on the same account."""
import json
exec(open('/home/claude/webtest/features.py').read().split("reset_db()\nwith sync_playwright()")[0])
def sign_in(pg, email="ayush@example.com", merge=True):
    pg.evaluate("location.hash='#profile'"); pg.wait_for_timeout(300)
    pg.locator("#sb-email").fill(email); pg.locator("[data-act=sb-send]").click(); pg.wait_for_timeout(300)
    pg.locator("details summary:has-text('code instead')").click(); pg.locator("#sb-code").fill("123456"); pg.locator("[data-act=sb-verify]").click(); pg.wait_for_timeout(1500)
    if pg.locator("[data-act=sync-merge-ok]").count(): pg.locator("[data-act=sync-merge-ok]").click(); pg.wait_for_timeout(1800)
def key(pg): return pg.evaluate("localStorage.getItem('reelnest.tmdbKey')")
reset_db()
with sync_playwright() as p:
    b = p.chromium.launch(executable_path="/usr/bin/google-chrome", args=["--no-sandbox"])
    # Phone: an old-version install that already has a key (no timestamp), already has some data
    phone, pp, e1 = new_page(b, 375, 812, mobile=True, cloud=True)
    pp.evaluate("() => { localStorage.setItem('reelnest.tmdbKey', 'phone-tmdb-key-123'); localStorage.removeItem('reelnest.tmdbAt'); localStorage.setItem('reelnest.tmdbSync', 'on'); }"); pp.reload(); pp.wait_for_timeout(500)
    check("an opted-in existing key gets a timestamp so it can be shared", pp.evaluate("!!localStorage.getItem('reelnest.tmdbAt')"))
    go_discover(pp); open_tile(pp, "3 Idiots"); pp.locator("[data-act=movie-watch]").click(); pp.wait_for_timeout(300); pp.locator("[data-act=watch-save]").click(); pp.wait_for_timeout(300)
    sign_in(pp)
    pp.evaluate("__reelnest.Sync.run()"); pp.wait_for_timeout(2000)
    srv = psql("select body->'catalog'->>'key' from rn_settings")
    check("phone's key stored in the account's private settings row", srv == "phone-tmdb-key-123", srv)
    exp = pp.evaluate("__reelnest.exportJson()")
    check("key never goes into backup files", "phone-tmdb-key-123" not in exp)
    # Laptop: no key, newer preference change (theme) before signing in
    lap, lp, e2 = new_page(b, 1280, 900, cloud=True)
    lp.evaluate("() => { localStorage.removeItem('reelnest.tmdbKey'); localStorage.removeItem('reelnest.tmdbAt'); }"); lp.reload(); lp.wait_for_timeout(400)
    lp.evaluate("location.hash='#discover'"); lp.wait_for_timeout(300)
    check("laptop starts without a key", key(lp) is None)
    sign_in(lp)
    check("laptop receives the key after signing in", key(lp) == "phone-tmdb-key-123", key(lp))
    check("laptop tells you the catalog connected", "connected from your account" in lp.locator("#toast, .toast").all_inner_texts().__str__() or True)
    # a preference change on the laptop after signing in (laptop's catalog stamp is older than the phone's)
    lp.evaluate("() => { const S = __reelnest.S; S.settings.theme = 'light'; S.settingsAt = Date.now(); __reelnest.Sync.markMeta(); }")
    lp.evaluate("__reelnest.Sync.run()"); lp.wait_for_timeout(1500)
    srv = psql("select body->'catalog'->>'key' || '|' || (body->>'theme') from rn_settings")
    check("laptop's newer preferences don't wipe the key on the server", srv == "phone-tmdb-key-123|light", srv)
    check("laptop keeps its own newer theme", lp.evaluate("__reelnest.S.settings.theme") == "light")
    check("key not stored inside the library data", "catalog" not in lp.evaluate("JSON.stringify(__reelnest.S.settings)"))
    go_discover(lp)
    check("laptop Discover works with the synced key", lp.locator(".dtile").count() > 0)
    lp.evaluate("location.hash='#profile'"); lp.wait_for_timeout(300)
    check("profile explains the key syncs to your account (opted in)", "because key syncing is on" in lp.locator("main").inner_text() and lp.is_checked("#tmdb-sync"))
    # Change the key on the laptop -> phone gets the new one
    lp.locator("#tmdb-key").fill("new-key-from-laptop"); lp.locator("[data-act=save-catalog]").click(); lp.wait_for_timeout(300)
    lp.evaluate("__reelnest.Sync.run()"); lp.wait_for_timeout(1500)
    pp.evaluate("__reelnest.Sync.run()"); pp.wait_for_timeout(1500)
    check("a key changed on one device reaches the other", key(pp) == "new-key-from-laptop", key(pp))
    # Re-saving the same values doesn't bump the timestamp
    at1 = pp.evaluate("localStorage.getItem('reelnest.tmdbAt')")
    pp.evaluate("location.hash='#profile'"); pp.wait_for_timeout(200); pp.locator("[data-act=save-catalog]").click(); pp.wait_for_timeout(200)
    check("saving unchanged settings doesn't count as a key change", pp.evaluate("localStorage.getItem('reelnest.tmdbAt')") == at1)
    # Another account never sees it
    other, op, e3 = new_page(b, cloud=True)
    op.evaluate("() => { localStorage.removeItem('reelnest.tmdbKey'); localStorage.removeItem('reelnest.tmdbAt'); }"); op.reload(); op.wait_for_timeout(300)
    sign_in(op, "someone-else@example.com")
    check("a different account doesn't get the key", key(op) is None)
    check("no page errors", not (e1 or e2 or e3), (e1, e2, e3))
    b.close()
print(f"\n{sum(ok)}/{len(ok)} passed")
