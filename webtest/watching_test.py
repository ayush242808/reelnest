"""'Watching': series detected automatically, a Watching button for movies, a Watching list in Library."""
src = open("/home/claude/webtest/e2e.py").read()
exec(src[: src.index("reset_db()\nwith sync_playwright")])
PID = "tmdb:series:61145"
def lib_ids(pg): return pg.evaluate("() => [...document.querySelectorAll('main [data-act=open]')].map(b => b.dataset.id)")
def status(pg, k): return pg.evaluate("(k) => __reelnest.S.states[k] && __reelnest.S.states[k].status", k)

reset_db()
with sync_playwright() as p:
    b = p.chromium.launch(executable_path="/usr/bin/google-chrome", args=["--no-sandbox"])
    ctx, pg, errs = new_page(b, w=390, h=844)
    add_panchayat(pg)
    # older data: episodes watched, status never updated
    pg.evaluate(f"""() => {{ __reelnest.markEpisodes('{PID}', ['tmdb:ep:9001']); const s = __reelnest.S.states['{PID}']; s.status = 'NOT_STARTED'; s.statusAt = Date.now(); __reelnest.Persist.touch('{PID}'); }}""")
    pg.wait_for_timeout(1500); pg.reload(); pg.wait_for_timeout(1200)
    check("W1 a series with episodes watched is detected as Watching", status(pg, PID) == "WATCHING", status(pg, PID))
    # a movie
    mid = pg.evaluate("() => __reelnest.createManual({title:'Half Seen Film', type:'MOVIE', isAnime:false, year:'2024', runtime:'', lang:'', country:'', release:'', originalTitle:'', overview:'', seasons:'', perSeason:''})")
    pg.evaluate("(k) => { const s = __reelnest.S.states[k]; if (s) { s.status = 'NOT_STARTED'; } }", mid)
    tab(pg, "library"); pg.locator(f"main [data-act=open][data-id='{mid}']").click(); pg.wait_for_timeout(700)
    btn = pg.locator("[data-act=movie-watching]")
    check("W2 a movie page has a Watching button next to Mark watched", btn.count() == 1 and btn.get_attribute("aria-pressed") == "false" and pg.locator("[data-act=movie-watch]").count() == 1)
    btn.click(); pg.wait_for_timeout(300)
    check("W2 tapping it marks the movie Watching", status(pg, mid) == "WATCHING" and pg.locator("[data-act=movie-watching]").get_attribute("aria-pressed") == "true")
    pg.locator("[data-act=back]").first.click(); pg.wait_for_timeout(300); tab(pg, "library")
    chip = pg.locator("[data-act=lib-watching]")
    check("W3 Library has a Watching chip with the count", chip.count() == 1 and " ".join(chip.inner_text().split()) == "Watching 2", chip.inner_text() if chip.count() else None)
    chip.click(); pg.wait_for_timeout(300)
    ids = lib_ids(pg)
    check("W3 tapping it lists exactly what you're watching (movie + series)", sorted(ids) == sorted([mid, PID]), ids)
    check("W3 ...and each shows 'Watching'", pg.locator("main", has_text="Watching").count() >= 1)
    # finishing the movie completes it
    pg.locator(f"main [data-act=open][data-id='{mid}']").click(); pg.wait_for_timeout(600)
    pg.locator("[data-act=movie-watch]").click(); pg.wait_for_timeout(400); pg.locator("[data-act=watch-save]").click(); pg.wait_for_timeout(400)
    check("W4 marking the movie watched moves it to Completed", status(pg, mid) == "COMPLETED", status(pg, mid))
    undo = pg.locator(".toast button", has_text="Undo")
    if undo.count(): undo.click(); pg.wait_for_timeout(300)
    check("W4 Undo puts it back to Watching", status(pg, mid) == "WATCHING", status(pg, mid))
    pg.locator("[data-act=movie-watching]").click(); pg.wait_for_timeout(300)
    check("W5 tapping Watching again takes it off the list", status(pg, mid) == "NOT_STARTED")
    pg.locator("[data-act=back]").first.click(); pg.wait_for_timeout(300); tab(pg, "library")
    check("W5 ...and the chip updates", " ".join(pg.locator("[data-act=lib-watching]").inner_text().split()) == "Watching 1")
    pg.evaluate(f"() => __reelnest.setField('{PID}', 'interest', 'NOT_INTERESTED')"); tab(pg, "home"); tab(pg, "library")
    check("W6 Not interested titles aren't counted as Watching", " ".join(pg.locator("[data-act=lib-watching]").inner_text().split()) == "Watching 0")
    check("no page errors", not errs, errs[:3])
    b.close()
print(f"\n{sum(1 for r in results if r[1])}/{len(results)} passed")
