"""'Not interested': hide a title from Discover for good, organised in Library."""
src = open("/home/claude/webtest/e2e.py").read()
exec(src[: src.index("reset_db()\nwith sync_playwright")])
PID = "tmdb:series:61145"
def disc_keys(pg): return pg.evaluate("() => [...document.querySelectorAll('.drow .dtile-open, .dgrid .dtile-open')].map(b => b.dataset.key)")
def where(pg): return pg.evaluate("() => __reelnest.UI.detail ? 'title' : __reelnest.UI.tab")

reset_db()
with sync_playwright() as p:
    b = p.chromium.launch(executable_path="/usr/bin/google-chrome", args=["--no-sandbox"])
    ctx, pg, errs = new_page(b, w=390, h=844)
    tab(pg, "discover"); pg.wait_for_timeout(1200)
    keys = disc_keys(pg)
    first = keys[0]
    pg.locator(f".drow .dtile-open[data-key='{first}']").first.click(); pg.wait_for_timeout(1200)
    btn = pg.locator("[data-act=not-interested]")
    check("N1 a title opened from Discover has a 'Not interested' button at the top", btn.count() == 1 and btn.get_attribute("aria-pressed") == "false" and btn.bounding_box()["y"] < 80, btn.bounding_box() if btn.count() else None)
    btn.click(); pg.wait_for_timeout(600)
    check("N2 it takes you back to Discover", where(pg) == "discover")
    check("N2 ...and the title is gone from Discover", first not in disc_keys(pg), first)
    check("N2 ...with a message and Undo", pg.locator(".toast", has_text="Not interested").count() == 1 and pg.locator(".toast button", has_text="Undo").count() == 1)
    pg.locator(".toast button", has_text="Undo").click(); pg.wait_for_timeout(500)
    check("N3 Undo brings it back and doesn't leave it in your library", first in disc_keys(pg) and pg.evaluate("(k) => !__reelnest.S.states[k]", first))
    # on the watchlist first, then dismissed
    pg.locator(f".drow .dtile-open[data-key='{first}']").first.click(); pg.wait_for_timeout(1000)
    pg.evaluate("(k) => __reelnest.setField(k, 'watchlist', true)", first)
    pg.locator("[data-act=not-interested]").click(); pg.wait_for_timeout(600)
    check("N4 marking it takes it off your watchlist", pg.evaluate("(k) => [__reelnest.S.states[k].interest, __reelnest.S.states[k].watchlist]", first) == ["NOT_INTERESTED", False])
    pg.reload(); pg.wait_for_timeout(900); tab(pg, "discover"); pg.wait_for_timeout(900)
    check("N5 still hidden after a reload (saved)", first not in disc_keys(pg))
    title = pg.evaluate("(k) => __reelnest.S.works[k].title", first)
    pg.fill("#disc-q", title); pg.wait_for_timeout(1300)
    badge = pg.locator(f".dtile-open[data-key='{first}']").locator("xpath=..").locator(".dtile-badge")
    check("N6 searching for it still finds it, labelled 'Not interested'", first in disc_keys(pg) and badge.count() == 1 and "Not interested" in badge.inner_text(), (title, disc_keys(pg)[:4]))
    pg.fill("#disc-q", ""); pg.wait_for_timeout(500)
    # Library
    add_panchayat(pg)
    tab(pg, "library"); pg.wait_for_timeout(300)
    lib = pg.evaluate("() => [...document.querySelectorAll('main [data-act=open]')].map(b => b.dataset.id)")
    chip = pg.locator("[data-act=lib-ni]")
    check("N7 Library keeps it out of the main list", first not in lib and PID in lib, lib)
    check("N7 ...and a 'Not interested' chip shows how many", chip.count() == 1 and " ".join(chip.inner_text().split()) == "Not interested 1", chip.inner_text() if chip.count() else None)
    chip.click(); pg.wait_for_timeout(300)
    lib2 = pg.evaluate("() => [...document.querySelectorAll('main [data-act=open]')].map(b => b.dataset.id)")
    check("N7 tapping it lists your Not interested titles", lib2 == [first], lib2)
    pg.locator(f"main [data-act=open][data-id='{first}']").click(); pg.wait_for_timeout(900)
    b2 = pg.locator("[data-act=not-interested]")
    check("N8 on its page the button shows it's marked", b2.get_attribute("aria-pressed") == "true")
    b2.click(); pg.wait_for_timeout(400)
    check("N8 tapping it again un-marks it", pg.evaluate("(k) => __reelnest.S.states[k].interest", first) == "UNCLASSIFIED" and b2.get_attribute("aria-pressed") == "false")
    pg.locator("[data-act=back]").first.click(); pg.wait_for_timeout(300)
    # Home: a series you were watching disappears from Continue watching / upcoming
    pg.evaluate(f"() => {{ __reelnest.setField('{PID}', 'status', 'WATCHING'); __reelnest.markEpisodes('{PID}', ['tmdb:ep:9001']); }}")
    tab(pg, "home"); pg.wait_for_timeout(300)
    before = pg.locator(".next-card").count()
    pg.evaluate(f"() => __reelnest.setField('{PID}', 'interest', 'NOT_INTERESTED')")
    tab(pg, "library"); tab(pg, "home"); pg.wait_for_timeout(300)
    check("N9 a series marked Not interested leaves Continue watching", before == 1 and pg.locator(".next-card").count() == 0, (before, pg.locator(".next-card").count()))
    check("N10 watch history is kept (only hidden)", pg.evaluate(f"() => Object.values(__reelnest.S.events).filter(e => e.workId === '{PID}' && e.deletedAt == null).length") == 1)
    check("no page errors", not errs, errs[:3])
    b.close()
